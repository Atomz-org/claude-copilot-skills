#!/usr/bin/env python3
"""Project a use-case into a WrenAI semantic-layer project — import, then enrich.

WrenAI (pinned as a submodule at external/WrenAI, installed as the `wrenai` wheel) already
ships a native dbt importer: `wren context import dbt` turns a dbt project's manifest.json +
catalog.json into a Wren MDL project — models, columns, relationships from `relationships`
tests, knowledge scaffolding. This script does **not** reimplement any of that. It runs the
native importer and then writes the one thing the importer cannot know: the business context
this repository already derives.

    importer (upstream, mechanical)          enrichment (this repo's artifacts)
    ---------------------------------        -------------------------------------------
    models/<name>/metadata.yml               knowledge/rules/ontology-concepts.md
    relationships.yml (dbt tests)              <- ontology/index.json
    knowledge/rules/general.md               knowledge/rules/column-contracts.md
    knowledge/sql/*.md seed pairs              <- ontology/column-memory.json
    wren_project.yml, AGENTS.md              knowledge/caveats/adapter-drift.md
                                               <- column-memory drift findings
                                             knowledge/rules/semantic-metrics.md
                                               <- manifest metrics (MetricFlow)
                                             cubes/<name>/metadata.yml
                                               <- manifest semantic models + catalog types

Ownership is disjoint on purpose: re-running the importer with `--force` regenerates its
files and only its files, and this script's files carry a generated-by header naming the
regeneration command. Hand-authored knowledge belongs in *other* filenames — both layers
leave unknown files alone (they are reported as `stale`, never deleted).

Generation happens in a scratch directory beside the target and is diffed file-by-file, for
the same reason the other emitters do it: `--check` must write nothing, a re-run must change
nothing, and the changed-file list is the report. Nothing run-dependent goes into the tree.

Cube types are read from catalog.json — the warehouse's own answer — never guessed (rule 5).
A measure whose aggregation has no direct SQL projection, or a dimension whose expression is
not a bare catalog column, is skipped and counted in the payload rather than approximated.

Inputs that are missing produce a `skip` with the way out, not a failure: no dbt_project, no
manifest (`dbt parse`), no catalog.json (`dbt docs generate`), no `wren` CLI
(pip install -r requirements.txt). The CLI is resolved from $WREN_CLI, then PATH, then the
repository's .venv-wren/.

Usage:
    python3 scripts/wren_context_sync.py --use-case example-order-revenue-mart
    python3 scripts/wren_context_sync.py --use-case <slug> --check --format json
"""

from __future__ import annotations

import argparse
import contextlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Iterator, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _manifest import Manifest, die, load_json  # noqa: E402

REPO = Path(__file__).resolve().parent.parent

GENERATED_HEADER = (
    "<!-- Generated by scripts/wren_context_sync.py — do not hand-edit. "
    "Regenerate: python3 scripts/use_case_sync.py --use-case {slug} --stage wren -->"
)

# Files the upstream importer owns and regenerates under --force. Everything else in the
# project tree that we did not generate is someone's hand-authored context: report, never
# touch. `apps/` is agent-authored GenBI output; `.wren/` and `target/` are derived state.
UNTOUCHED_DIRS = {"apps", ".wren", "target"}

# MetricFlow aggregation -> SQL projection for a cube measure, with the result type the
# aggregation itself determines. Anything not listed has no faithful single-expression
# projection (percentile, median, sum_boolean) and is skipped, counted, and reported.
AGG_SQL = {
    "sum": ("SUM({x})", "DOUBLE"),
    "avg": ("AVG({x})", "DOUBLE"),
    "average": ("AVG({x})", "DOUBLE"),
    "count": ("COUNT({x})", "BIGINT"),
    "count_distinct": ("COUNT(DISTINCT {x})", "BIGINT"),
    "min": ("MIN({x})", None),  # result type = column type, read from the catalog
    "max": ("MAX({x})", None),
}


def use_case_dir(slug: str) -> Optional[Path]:
    matches = [p for p in REPO.glob(f"skill-packs/*/use-cases/{slug}") if p.is_dir()]
    return matches[0] if matches else None


def find_wren_cli() -> Optional[str]:
    env = os.environ.get("WREN_CLI")
    if env and Path(env).exists():
        return env
    on_path = shutil.which("wren")
    if on_path:
        return on_path
    local = REPO / ".venv-wren" / "bin" / "wren"
    return str(local) if local.exists() else None


def run_wren(cli: str, args: List[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        [cli, *args], capture_output=True, text=True, timeout=600, cwd=REPO,
    )


