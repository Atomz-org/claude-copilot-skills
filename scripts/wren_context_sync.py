def sync(slug: str, manifest_arg: Optional[str], check: bool) -> Dict[str, Any]:
    use_case = use_case_dir(slug)
    if not use_case:
        die(f"no such use-case under skill-packs/*/use-cases/: {slug}")

    payload: Dict[str, Any] = {"use_case": slug, "status": "skip"}

    if not (use_case / "dbt_project").exists():
        payload["reason"] = "no dbt_project yet"
        return payload
    default_manifest = use_case / "dbt_project/target/manifest.json"
    manifest_path = Path(manifest_arg) if manifest_arg else default_manifest
    # The wrenai importer always reads <dbt_project>/target/ itself; honoring a foreign
    # --manifest here would sanitize and enrich from one manifest while the importer
    # reads another — two internally consistent halves of different generations.
    if manifest_arg and manifest_path.resolve() != default_manifest.resolve():
        payload["reason"] = (
            "--manifest points outside dbt_project/target/ — the wren importer reads "
            "the project's own target; re-run dbt parse there instead"
        )
        return payload
    if not manifest_path.exists():
        payload["reason"] = "no manifest — dbt parse (or artifacts/refresh.sh)"
        return payload
    catalog_path = manifest_path.parent / "catalog.json"
    if not catalog_path.exists():
        payload["reason"] = "no catalog.json — dbt docs generate against the local target"
        return payload
    cli = find_wren_cli()
    if not cli:
        payload["reason"] = "wren CLI not installed — pip install -r requirements.txt"
        return payload

    scratch = use_case / ".wren.tmp"
    try:
        stats = generate(cli, use_case, slug, manifest_path, catalog_path, scratch)
        changed, deleted, stale = diff_and_sync(scratch, use_case / "wren", check)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    payload.update(stats)
    payload["status"] = "changed" if (changed or deleted) else "ok"
    payload["changed"] = changed
    payload["deleted"] = deleted
    payload["stale"] = stale
    return payload


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(
        description="Generate the WrenAI semantic-layer project for a use-case: "
                    "native dbt import plus ontology/contract/metric enrichment.",
    )
    p.add_argument("--use-case", required=True, help="slug under skill-packs/*/use-cases/")
    p.add_argument("--manifest", help="manifest.json (default: <project>/target/manifest.json)")
    p.add_argument("--check", action="store_true",
                   help="write nothing; report what would change")
    p.add_argument("--format", choices=("text", "json"), default="text")
    args = p.parse_args(argv)

    payload = sync(args.use_case, args.manifest, args.check)

    if args.format == "json":
        print(json.dumps(payload, ensure_ascii=False))
    else:
        status = payload["status"]
        if status == "skip":
            print(f"skip  {payload['use_case']}: {payload['reason']}")
        else:
            print(
                f"{status:<5} {payload['use_case']}: {payload.get('models', 0)} models, "
                f"{payload.get('relationships', 0)} relationships, "
                f"{payload.get('cubes', 0)} cubes, "
                f"{payload.get('knowledge_files', 0)} knowledge files, "
                f"{payload.get('validate_warnings', 0)} validate warning(s)"
            )
            for rel in payload.get("changed", []):
                print(f"  changed  wren/{rel}")
            for rel in payload.get("deleted", []):
                print(f"  deleted  wren/{rel} (generation-owned orphan)")
            for rel in payload.get("stale", []):
                print(f"  stale    wren/{rel} (hand-authored; left alone)")
            skipped = payload.get("cubes_skipped", [])
            if skipped:
                print(f"  {len(skipped)} cube part(s) skipped rather than approximated:")
                for reason in skipped[:10]:
                    print(f"    - {reason}")

    if payload["status"] == "changed" and args.check:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
