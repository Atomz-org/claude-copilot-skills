REPO = Path(__file__).resolve().parent.parent

GENERATED_HEADER = (
    "<!-- Generated by scripts/wren_context_sync.py — do not hand-edit. "
    "Regenerate: python3 scripts/use_case_sync.py --use-case {slug} --stage wren -->"
)

# Files the upstream importer owns and regenerates under --force. Everything else in the
# project tree that we did not generate is someone's hand-authored context: report, never
# touch. `apps/` is agent-authored GenBI output; `.wren/` and `target/` are derived state.
UNTOUCHED_DIRS = {"apps", ".wren", "target"}

# MetricFlow aggregation -> SQL projection for a cube measure, with the result type the
# aggregation itself determines. Anything not listed has no faithful single-expression
# projection (percentile, median, sum_boolean) and is skipped, counted, and reported.
AGG_SQL = {
    "sum": ("SUM({x})", "DOUBLE"),
    "avg": ("AVG({x})", "DOUBLE"),
    "average": ("AVG({x})", "DOUBLE"),
    "count": ("COUNT({x})", "BIGINT"),
    "count_distinct": ("COUNT(DISTINCT {x})", "BIGINT"),
    "min": ("MIN({x})", None),  # result type = column type, read from the catalog
    "max": ("MAX({x})", None),
}


def use_case_dir(slug: str) -> Optional[Path]:
    matches = [p for p in REPO.glob(f"skill-packs/*/use-cases/{slug}") if p.is_dir()]
    return matches[0] if matches else None


def find_wren_cli() -> Optional[str]:
    env = os.environ.get("WREN_CLI")
    if env and Path(env).exists():
        return env
    on_path = shutil.which("wren")
    if on_path:
        return on_path
    local = REPO / ".venv-wren" / "bin" / "wren"
    return str(local) if local.exists() else None


def run_wren(cli: str, args: List[str]) -> subprocess.CompletedProcess:
    # Per-call budget deliberately below stage_wren's whole-script timeout in
    # use_case_sync.py (1800s): four wren calls at 300s each leave headroom, so the outer
    # timeout can never SIGKILL this process while the run_results sanitizer is open.
    return subprocess.run(
        [cli, *args], capture_output=True, text=True, timeout=300, cwd=REPO,
    )


def _tail(proc: subprocess.CompletedProcess) -> str:
    lines = (proc.stderr or proc.stdout).strip().splitlines()
    return lines[-1] if lines else "no output"


