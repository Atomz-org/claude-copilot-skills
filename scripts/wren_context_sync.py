def concepts_markdown(index: Dict[str, Any], slug: str) -> Optional[str]:
    concepts = index.get("concepts") or []
    if not concepts:
        return None
    lines = [GENERATED_HEADER.format(slug=slug), "", "# Ontology concepts", ""]
    lines += [
        "Business concepts this use-case's ontology defines, and which connectors supply",
        "each one. A concept named here is the conformed entity; the dbt models that",
        "implement it per connector are listed in `column-contracts.md`.", "",
    ]
    for c in sorted(concepts, key=lambda x: x.get("concept", "")):
        implemented = ", ".join(sorted(c.get("implemented_by") or [])) or "none yet"
        planned = ", ".join(sorted(c.get("planned_by") or []))
        line = f"- **{c.get('concept')}** ({c.get('core_class', '?')}) — implemented by: {implemented}"
        if planned:
            line += f"; planned: {planned}"
        lines.append(line)
    gaps = index.get("gaps") or []
    if gaps:
        lines += ["", "## Coverage gaps", ""]
        for g in sorted(gaps, key=lambda x: x.get("concept", "")):
            lines.append(f"- {g.get('concept')}: {g.get('reason')}")
    return "\n".join(lines) + "\n"


def contracts_markdown(memory: Dict[str, Any], slug: str) -> Optional[str]:
    contracts = memory.get("contracts") or []
    if not contracts:
        return None
    lines = [GENERATED_HEADER.format(slug=slug), "", "# Column contracts", ""]
    lines += [
        "Conformed column lists per concept, derived from parsed column lineage across",
        "every connector's adapter model. When writing SQL against a conformed concept,",
        "these are the column names that exist on every supplier.", "",
    ]
    for c in sorted(contracts, key=lambda x: x.get("concept", "")):
        adapters = c.get("adapters") or {}
        supplier_note = ", ".join(
            f"{k} ({v})" for k, v in sorted(adapters.items())
        )
        lines.append(f"## {c.get('concept')}")
        lines.append("")
        if supplier_note:
            lines.append(f"Suppliers: {supplier_note}")
        conformed = c.get("conformed") or []
        if conformed:
            lines.append(f"Conformed columns ({len(conformed)}): " + ", ".join(conformed))
        partial = c.get("partial_for") or []
        if partial:
            lines.append(
                f"Partial (macro-generated column list, cannot be fully named): "
                + ", ".join(sorted(partial))
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def drift_markdown(memory: Dict[str, Any], slug: str) -> Optional[str]:
    drift = memory.get("drift") or []
    if not drift:
        return None
    lines = [GENERATED_HEADER.format(slug=slug), "", "# Adapter column drift", ""]
    lines += [
        "Known disagreements between connector adapters that supply the same concept.",
        "SQL that unions or compares across these connectors must account for them.", "",
    ]
    for d in sorted(drift, key=lambda x: (x.get("concept", ""), x.get("column", ""))):
        missing = ", ".join(sorted(d.get("missing_from") or [])) or "-"
        carried = ", ".join(sorted(d.get("carried_by") or [])) or "-"
        lines.append(
            f"- **{d.get('concept')}.{d.get('column')}** ({d.get('confidence')}) — "
            f"carried by: {carried}; missing from: {missing}"
        )
    return "\n".join(lines) + "\n"


def metrics_markdown(man: Manifest, slug: str) -> Optional[str]:
    metrics = man.metrics
    if not metrics:
        return None
    lines = [GENERATED_HEADER.format(slug=slug), "", "# Semantic-layer metrics", ""]
    lines += [
        "Metric definitions from the dbt semantic layer (MetricFlow). These are the",
        "canonical definitions — a query answering a metric question should reproduce",
        "the definition below, not invent a variant (one metric, one definition).", "",
    ]
    for key in sorted(metrics):
        m = metrics[key]
        name = m.get("name", key)
        lines.append(f"## {name}")
        lines.append("")
        label = m.get("label")
        if label and label != name:
            lines.append(f"Label: {label}")
        lines.append(f"Type: {m.get('type', '?')}")
        desc = " ".join((m.get("description") or "").split())
        if desc:
            lines.append(f"Definition: {desc}")
        params = m.get("type_params") or {}
        expr = params.get("expr")
        if expr:
            lines.append(f"Formula: `{expr}`")
        num, den = params.get("numerator"), params.get("denominator")
        if num or den:
            # A ratio leg can carry its own filter and alias — emea_revenue_share's
            # numerator is revenue *filtered to EMEA*. Dropping that renders the metric
            # as revenue/revenue, a wrong definition presented as canonical.
            lines.append(f"Ratio: {_metric_ref(num)} / {_metric_ref(den)}")
        flt = _filter_sql(m.get("filter"))
        if flt:
            lines.append(f"Filter: `{flt}`")
        lines.append("")
    return "\n".join(lines) + "\n"


def _filter_sql(flt: Any) -> str:
    """Flatten MetricFlow's filter shapes to the SQL templates they carry."""
    if not flt:
        return ""
    if isinstance(flt, dict):
        templates = [
            w.get("where_sql_template", "") for w in flt.get("where_filters", [])
            if isinstance(w, dict)
        ]
        flt = " AND ".join(t for t in templates if t) or flt.get("where_sql_template", "")
    return " ".join(str(flt).split())


def _metric_ref(side: Any) -> str:
    if not isinstance(side, dict):
        return f"`{side}`"
    ref = f"`{side.get('name', '?')}`"
    leg_filter = _filter_sql(side.get("filter"))
    if leg_filter:
        ref += f" filtered by `{leg_filter}`"
    if side.get("alias"):
        ref += f" (as {side['alias']})"
    return ref


def _model_name(man: Manifest, unique_id: str) -> str:
    """The model's declared name — from the manifest node, never the unique_id.

    A versioned model's unique_id is `model.<pkg>.<name>.v<version>`, so splitting the
    id string yields `v2` as the "name". The node's own `name` field is what the wrenai
    importer emits as the Wren model name, so it is the only join key that holds.
    """
    node = man.all_nodes().get(unique_id) or {}
    return node.get("name") or unique_id.rsplit(".", 1)[-1]


def build_cubes(man: Manifest, catalog: Dict[str, Any],
                slug: str) -> Tuple[Dict[str, str], List[str]]:
    """One cube per dbt semantic model, typed from the warehouse catalog."""
    cubes: Dict[str, str] = {}
    skipped: List[str] = []
    rejected: set = set()
    catalog_nodes = catalog.get("nodes") or {}

    for key in sorted(man.semantic_models):
        sm = man.semantic_models[key]
        name = sm.get("name") or key.rsplit(".", 1)[-1]
        if name in cubes or name in rejected:
            skipped.append(f"{name}: cube name collides across semantic models "
                           f"({key}); rename one — no winner is emitted silently")
            cubes.pop(name, None)
            rejected.add(name)
            continue
        model_ids = [u for u in (sm.get("depends_on") or {}).get("nodes", [])
                     if u.startswith("model.")]
        if len(model_ids) != 1:
            skipped.append(f"{name}: semantic model does not sit on exactly one model")
            continue
        base_object = _model_name(man, model_ids[0])
        catalog_cols = {
            c.lower(): (meta or {}).get("type", "")
            for c, meta in ((catalog_nodes.get(model_ids[0]) or {}).get("columns") or {}).items()
        }
        if not catalog_cols:
            skipped.append(f"{name}: {base_object} not in catalog.json")
            continue

        def column_type(expression: str) -> Optional[str]:
            return catalog_cols.get(expression.strip().lower())

        measures, dimensions, time_dimensions = [], [], []
        for ms in sm.get("measures") or []:
            agg = (ms.get("agg") or "").lower()
            template = AGG_SQL.get(agg)
            expr = (ms.get("expr") or ms.get("name") or "").strip()
            if not template or not expr:
                skipped.append(f"{name}.{ms.get('name')}: no faithful projection for agg '{agg}'")
                continue
            sql, result_type = template
            if result_type is None:  # min/max: result type is the column's own
                result_type = column_type(expr)
                if not result_type:
                    skipped.append(f"{name}.{ms.get('name')}: '{expr}' not a catalog column")
                    continue
            measures.append({
                "name": ms["name"], "expression": sql.format(x=expr), "type": result_type,
            })
        for dim in sm.get("dimensions") or []:
            expr = (dim.get("expr") or dim.get("name") or "").strip()
            ctype = column_type(expr)
            if not ctype:
                skipped.append(f"{name}.{dim.get('name')}: '{expr}' not a catalog column")
                continue
            entry = {"name": dim["name"], "expression": expr, "type": ctype}
            if (dim.get("type") or "").lower() == "time":
                time_dimensions.append(entry)
            else:
                dimensions.append(entry)

        if not measures:
            skipped.append(f"{name}: no projectable measures")
            continue
        description = " ".join((sm.get("description") or "").split()) or (
            f"Projected from dbt semantic model '{name}'."
        )
        cubes[name] = cube_yaml(name, base_object, description,
                                measures, dimensions, time_dimensions)
    return cubes, skipped


