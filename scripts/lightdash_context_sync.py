def _test_index(man: Manifest) -> Tuple[Set[Tuple[str, str]], Set[Tuple[str, str]]]:
    """(model_uid, column) pairs carrying a `unique` / `not_null` test."""
    unique: Set[Tuple[str, str]] = set()
    not_null: Set[Tuple[str, str]] = set()
    for node in man.tests().values():
        meta = node.get("test_metadata") or {}
        attached = node.get("attached_node")
        column = node.get("column_name")
        if not attached or not column:
            continue
        if meta.get("name") == "unique":
            unique.add((attached, column))
        elif meta.get("name") == "not_null":
            not_null.add((attached, column))
    return unique, not_null


def _declared(node: Dict[str, Any], name: str) -> str:
    """The model's own declared casing for a column name.

    dbt and the warehouses match test columns case-insensitively, so a relationships
    test may say `stockPointId` where the model declares `StockPointId` — and a
    Lightdash `${table.column}` reference is case-sensitive, so the test's casing
    dangles. The declared name is the model's own fact, not an invention. Measured:
    three enhanza explores compiled PARTIAL_SUCCESS on exactly this before the fix.
    """
    cols = node.get("columns") or {}
    if name in cols:
        return name
    lowered = {c.lower(): c for c in cols}
    return lowered.get(name.lower(), name)


def derive_joins(
    man: Manifest,
) -> Tuple[Dict[str, List[Dict[str, str]]], List[str]]:
    """`meta.joins` per child model, from the manifest's relationships tests.

    Child → parent, the direction the test declares. The parent is resolved from
    `depends_on.nodes`, never by regexing the jinja in `kwargs.to` — the same rule the
    graphify emitters follow, because a name rule mints wrong nodes silently.
    """
    unique, _ = _test_index(man)
    joins: Dict[str, List[Dict[str, str]]] = {}
    skipped: List[str] = []
    seen: Set[Tuple[str, str, str, str]] = set()

    for node in man.tests().values():
        meta = node.get("test_metadata") or {}
        if meta.get("name") != "relationships":
            continue
        child_uid = node.get("attached_node") or ""
        child = man.nodes.get(child_uid) or {}
        if child.get("resource_type") != "model":
            skipped.append(f"{node.get('name', '?')}: attached to a non-model")
            continue
        parents = [
            uid
            for uid in (node.get("depends_on") or {}).get("nodes", [])
            if uid != child_uid and uid.startswith("model.")
        ]
        if len(parents) != 1:
            skipped.append(
                f"{child.get('name')}: {len(parents)} model parents, expected one"
            )
            continue
        parent_uid = parents[0]
        parent = man.nodes.get(parent_uid) or {}
        fk = node.get("column_name")
        field = (meta.get("kwargs") or {}).get("field")
        if not fk or not field:
            skipped.append(
                f"{child.get('name')} -> {parent.get('name')}: test carries no "
                "column/field pair"
            )
            continue

        fk = _declared(child, fk)
        field = _declared(parent, field)
        key = (child.get("name", ""), parent.get("name", ""), fk, field)
        if key in seen:
            continue
        seen.add(key)

        entry: Dict[str, str] = {
            "join": parent["name"],
            "sql_on": f"${{{child['name']}.{fk}}} = ${{{parent['name']}.{field}}}",
            "type": "left",
            "_fk": fk,
            "_field": field,
        }
        # Cardinality only where a unique test states it; omitted, never guessed.
        if (parent_uid, field) in unique:
            entry["relationship"] = (
                "one-to-one" if (child_uid, fk) in unique else "many-to-one"
            )
        joins.setdefault(child["name"], []).append(entry)

    # Role-playing dimensions: two FKs to one parent are ordinary dbt and fatal
    # Lightdash — an explore may join a table once unless each join carries an
    # alias. The alias is derived from the test's own FK column (content, not
    # invention), and sql_on must reference the alias: the compiler registers the
    # joined table under `alias || table`.
    for child_name, entries in joins.items():
        by_parent: Dict[str, List[Dict[str, str]]] = {}
        for entry in entries:
            by_parent.setdefault(entry["join"], []).append(entry)
        for parent_name, group in by_parent.items():
            if len(group) > 1:
                for entry in group:
                    alias = f"{parent_name}_{entry['_fk']}"
                    entry["alias"] = alias
                    entry["sql_on"] = (
                        f"${{{child_name}.{entry['_fk']}}} = "
                        f"${{{alias}.{entry['_field']}}}"
                    )
        for entry in entries:
            entry.pop("_fk", None)
            entry.pop("_field", None)
        entries.sort(key=lambda e: (e["join"], e["sql_on"]))
    return joins, skipped


def derive_primary_keys(
    man: Manifest, participants: Set[str]
) -> Tuple[Dict[str, str], List[str]]:
    """One unique+not_null column per join participant, or nothing and a reason."""
    unique, not_null = _test_index(man)
    keys: Dict[str, str] = {}
    ambiguous: List[str] = []
    by_name = {n.get("name"): uid for uid, n in man.models().items()}
    for name in sorted(participants):
        uid = by_name.get(name)
        if not uid:
            continue
        candidates = sorted(
            col for (m, col) in unique if m == uid and (m, col) in not_null
        )
        if len(candidates) == 1:
            keys[name] = candidates[0]
        elif len(candidates) > 1:
            ambiguous.append(f"{name}: {len(candidates)} unique+not_null columns")
    return keys, ambiguous


def load_annotations(use_case: Path) -> Optional[List[Dict[str, Any]]]:
    path = use_case / "ontology/column-annotations.json"
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return None
    return data.get("columns") or []


def derive_column_meta(
    man: Manifest,
    annotations: Optional[List[Dict[str, Any]]],
    join_participants: Set[str],
) -> Tuple[Dict[Tuple[str, str], Dict[str, Any]], Dict[str, int]]:
    """(model, column) -> dimension meta, from annotations only.

    `hidden: true` for direct PII on every model that declares the column (rule 17).
    `ai_hint` (definition + additivity warning) only on join participants — the models
    a Lightdash explore actually surfaces — so hints land where an agent reads them
    instead of being sprayed over every staging model.
    """
    counts = {"pii_hidden": 0, "ai_hints": 0}
    if not annotations:
        return {}, counts

    facts: Dict[str, Dict[str, Any]] = {}
    for entry in annotations:
        name = entry.get("column")
        if name:
            facts[name] = entry

    out: Dict[Tuple[str, str], Dict[str, Any]] = {}
    for node in man.models().values():
        model = node.get("name", "")
        for column in (node.get("columns") or {}):
            fact = facts.get(column)
            if not fact:
                continue
            meta: Dict[str, Any] = {}
            if fact.get("pii") == "direct":
                meta["hidden"] = True
            if model in join_participants:
                hint_parts: List[str] = []
                definition = (fact.get("definition") or "").strip()
                if definition:
                    hint_parts.append(definition)
                additivity = fact.get("additivity")
                if additivity and additivity != "additive":
                    hint_parts.append(
                        f"Additivity: {additivity} — do not SUM without checking "
                        "the aggregation contract."
                    )
                if hint_parts:
                    meta["ai_hint"] = " ".join(hint_parts)
            if meta:
                out[(model, column)] = meta
                if meta.get("hidden"):
                    counts["pii_hidden"] += 1
                if meta.get("ai_hint"):
                    counts["ai_hints"] += 1
    return out, counts


