def find_lightdash_cli() -> Optional[str]:
    env = os.environ.get("LIGHTDASH_CLI")
    if env and Path(env).exists():
        return env
    from shutil import which

    on_path = which("lightdash")
    if on_path:
        return on_path
    local = REPO / ".lightdash-cli/node_modules/.bin/lightdash"
    if local.exists():
        return str(local)
    return None


