# MetricFlow coverage — mirror of the upstream translator's rules at the pinned release
# ---------------------------------------------------------------------------------------

_DIMENSION_REF = re.compile(r"Dimension\(\s*'([^']+)'")
_OTHER_REF = re.compile(r"(Entity|Metric)\(\s*'")


def _filter_templates(owner: Dict[str, Any]) -> List[str]:
    filt = owner.get("filter") or {}
    if isinstance(filt, str):
        return [filt]
    return [
        f.get("where_sql_template", "")
        for f in (filt.get("where_filters") or [])
        if isinstance(f, dict)
    ]


def _filter_verdict(owner: Dict[str, Any], home_entity: str) -> Optional[str]:
    """None when every filter stays on the metric's own model, else the reason."""
    for template in _filter_templates(owner):
        if _OTHER_REF.search(template):
            return "non-Dimension filter"
        for ref in _DIMENSION_REF.findall(template):
            prefix = ref.split("__")[0]
            if prefix not in (home_entity, "metric_time"):
                return f"filter references a joined model's dimension ({ref})"
    return None


def classify_metricflow(
    man: Manifest,
) -> Tuple[List[Dict[str, str]], List[Dict[str, str]], List[str]]:
    """(translated, skipped, saved_queries) per the upstream translator's own rules.

    Mirrors @lightdash/cli {CLI_PIN}'s metricFlow.ts: simple metrics translate
    (same-model where-filters included); ratio and derived translate when every input
    is a translated metric on the same semantic model with no time offset; cumulative,
    conversion, cross-model inputs, and time-offset inputs are skipped with a warning.
    """
    measure_home: Dict[str, str] = {}  # measure name -> semantic model name
    primary_entity: Dict[str, str] = {}  # semantic model name -> primary entity
    for sm in man.semantic_models.values():
        sm_name = sm.get("name", "")
        for measure in sm.get("measures") or []:
            measure_home[measure.get("name", "")] = sm_name
        for entity in sm.get("entities") or []:
            if entity.get("type") == "primary":
                primary_entity[sm_name] = entity.get("name", "")

    metrics = {m.get("name", ""): m for m in man.metrics.values()}
    verdicts: Dict[str, Tuple[Optional[str], Optional[str]]] = {}

    def verdict(name: str, trail: Tuple[str, ...] = ()) -> Tuple[Optional[str], Optional[str]]:
        """(home semantic model, None) when translatable, (None, reason) when not."""
        if name in verdicts:
            return verdicts[name]
        if name in trail:
            return None, "cyclic metric reference"
        metric = metrics.get(name)
        if metric is None:
            return None, "references an unknown metric"
        mtype = metric.get("type", "")
        params = metric.get("type_params") or {}
        result: Tuple[Optional[str], Optional[str]]

        if mtype == "simple":
            measure = (params.get("measure") or {}).get("name", "")
            home = measure_home.get(measure)
            if home is None:
                result = (None, f"measure {measure!r} is on no semantic model")
            else:
                reason = _filter_verdict(metric, primary_entity.get(home, ""))
                result = (home, None) if reason is None else (None, reason)
        elif mtype in ("ratio", "derived"):
            if mtype == "ratio":
                inputs = [params.get("numerator") or {}, params.get("denominator") or {}]
            else:
                inputs = list(params.get("metrics") or [])
            homes: Set[str] = set()
            reason = None
            for inp in inputs:
                if isinstance(inp, str):
                    inp = {"name": inp}
                if inp.get("offset_window") or inp.get("offset_to_grain"):
                    reason = f"input {inp.get('name')!r} carries a time offset"
                    break
                home, why = verdict(inp.get("name", ""), trail + (name,))
                if why is not None:
                    reason = f"input {inp.get('name')!r}: {why}"
                    break
                homes.add(home or "")
                inner = _filter_verdict(inp, primary_entity.get(home or "", ""))
                if inner is not None:
                    reason = f"input {inp.get('name')!r}: {inner}"
                    break
            if reason is None and len(homes) > 1:
                reason = "inputs live on different semantic models"
            if reason is None:
                outer = _filter_verdict(
                    metric, primary_entity.get(next(iter(homes), ""), "")
                )
                reason = outer
            result = (next(iter(homes), None), None) if reason is None else (None, reason)
        elif mtype in ("cumulative", "conversion"):
            result = (None, f"no {mtype} metric concept in Lightdash meta tags")
        else:
            result = (None, f"unknown metric type {mtype!r}")

        verdicts[name] = result
        return result

    translated: List[Dict[str, str]] = []
    skipped: List[Dict[str, str]] = []
    for name in sorted(metrics):
        metric = metrics[name]
        home, reason = verdict(name)
        if reason is None:
            translated.append(
                {"name": name, "type": metric.get("type", ""), "model": home or ""}
            )
        else:
            skipped.append(
                {"name": name, "type": metric.get("type", ""), "reason": reason}
            )
    saved = sorted(sq.get("name", "") for sq in man.saved_queries.values())
    return translated, skipped, saved


# ---------------------------------------------------------------------------------------
# YAML surgery — line-based insert/replace of marker-owned meta blocks
# ---------------------------------------------------------------------------------------

_RE_ENTRY = re.compile(r"^(\s*)-\s+name:\s*[\"']?([\w.]+)[\"']?\s*(?:#.*)?$")
_RE_KEY = re.compile(r"^(\s*)([A-Za-z_][\w]*):")


def _span_end(lines: List[str], start: int, indent: int) -> int:
    """First index >= start whose non-blank, non-comment line is indented `indent` or less.

    Comment lines are transparent at any column: a `#` is annotation, not structure.
    Found the hard way — a commented-out data_tests block at column 0 truncated a
    model body, and the last column's generated meta was silently withheld.
    """
    i = start
    while i < len(lines):
        stripped = lines[i].rstrip("\n")
        body = stripped.strip()
        if body and not body.startswith("#") and (
            len(stripped) - len(stripped.lstrip())
        ) <= indent:
            return i
        i += 1
    return i


def _render_model_meta(pad: str, meta: Dict[str, Any]) -> List[str]:
    out = [f"{pad}meta:  # {MARKER}\n"]
    joins = meta.get("joins") or []
    if joins:
        out.append(f"{pad}  joins:\n")
        for join in joins:
            out.append(f"{pad}    - join: {join['join']}\n")
            if "alias" in join:
                out.append(f"{pad}      alias: {join['alias']}\n")
            out.append(f"{pad}      sql_on: {join['sql_on']}\n")
            out.append(f"{pad}      type: {join['type']}\n")
            if "relationship" in join:
                out.append(f"{pad}      relationship: {join['relationship']}\n")
    if meta.get("primary_key"):
        out.append(f"{pad}  primary_key: {meta['primary_key']}\n")
    return out


def _render_column_meta(pad: str, meta: Dict[str, Any]) -> List[str]:
    out = [f"{pad}meta:  # {MARKER}\n", f"{pad}  dimension:\n"]
    if meta.get("hidden"):
        out.append(f"{pad}    hidden: true\n")
    if meta.get("ai_hint"):
        out.append(f"{pad}    ai_hint: {json.dumps(meta['ai_hint'])}\n")
    return out


def _apply_meta(
    lines: List[str],
    start: int,
    end: int,
    key_indent: int,
    desired: Optional[List[str]],
    report: Dict[str, List[str]],
    label: str,
) -> Tuple[List[str], int]:
    """Insert/replace/remove the marker-owned `meta:` inside one entry body.

    Returns the new lines and the shift in length. A `meta:` without the marker —
    including one nested inside `config:` — is a hand-authored decision: reported,
    never touched, and the desired block is withheld rather than emitted beside it.
    """
    pad = " " * key_indent
    i = start
    while i < end:
        stripped = lines[i].rstrip("\n")
        match = _RE_KEY.match(stripped)
        if match and len(match.group(1)) == key_indent:
            key = match.group(2)
            if key == "meta":
                owned = MARKER in stripped
                body_end = _span_end(lines, i + 1, key_indent)
                # Trailing blank/comment lines belong to the file, not the owned
                # block: trim them out of the replacement span so a comment after
                # generated meta is never deleted, and regeneration stays idempotent.
                while body_end > i + 1 and (
                    not lines[body_end - 1].strip()
                    or lines[body_end - 1].lstrip().startswith("#")
                ):
                    body_end -= 1
                if not owned:
                    report["hand_authored"].append(label)
                    return lines, 0
                new = list(desired) if desired else []
                if lines[i:body_end] == new:
                    return lines, 0
                shifted = lines[:i] + new + lines[body_end:]
                report["replaced" if desired else "removed"].append(label)
                return shifted, len(new) - (body_end - i)
            if key == "config":
                config_end = _span_end(lines, i + 1, key_indent)
                for line in lines[i + 1 : config_end]:
                    inner = line.rstrip("\n")
                    if re.match(r"^\s*meta\s*:", inner):
                        report["hand_authored"].append(label)
                        return lines, 0
                i = config_end
                continue
        i += 1

    if desired:
        insert_at = start
        shifted = lines[:insert_at] + list(desired) + lines[insert_at:]
        report["inserted"].append(label)
        return shifted, len(desired)
    return lines, 0


def rewrite_yaml(
    text: str,
    model_meta: Dict[str, Dict[str, Any]],
    column_meta: Dict[Tuple[str, str], Dict[str, Any]],
) -> Tuple[str, Dict[str, List[str]]]:
    """Apply the desired meta to one schema file, preserving everything else."""
    report: Dict[str, List[str]] = {
        "inserted": [],
        "replaced": [],
        "removed": [],
        "hand_authored": [],
        "found_models": [],
        "found_columns": [],
    }
    lines = text.splitlines(keepends=True)
    in_models = False
    entry_indent: Optional[int] = None
    i = 0
    while i < len(lines):
        stripped = lines[i].rstrip("\n")
        if re.match(r"^models:\s*$", stripped):
            in_models = True
            entry_indent = None
            i += 1
            continue
        # Only a new top-level mapping key (sources:, seeds:, ...) ends the models
        # section — a column-0 comment or a zero-indent `- name:` list entry does
        # not, though both start with a non-space character.
        if (
            in_models
            and stripped.strip()
            and not stripped[0].isspace()
            and _RE_KEY.match(stripped)
        ):
            in_models = False
        if not in_models:
            i += 1
            continue

        entry = _RE_ENTRY.match(stripped)
        if not entry or (entry_indent is not None and len(entry.group(1)) != entry_indent):
            i += 1
            continue
        if entry_indent is None:
            entry_indent = len(entry.group(1))
        model = entry.group(2)
        key_indent = entry_indent + 2
        body_start = i + 1
        body_end = _span_end(lines, body_start, entry_indent)
        report["found_models"].append(model)

        desired = model_meta.get(model)
        rendered = _render_model_meta(" " * key_indent, desired) if desired else None
        lines, shift = _apply_meta(
            lines, body_start, body_end, key_indent,
            rendered, report, model,
        )
        body_end += shift

        # Columns of this model, inside the (possibly shifted) body.
        j = body_start
        while j < body_end:
            col_key = _RE_KEY.match(lines[j].rstrip("\n"))
            if col_key and col_key.group(2) == "columns" and len(col_key.group(1)) == key_indent:
                cols_end = _span_end(lines, j + 1, key_indent)
                k = j + 1
                # Discover the column-entry indent from the first entry, the same
                # way entry_indent is discovered for models — files indent list
                # items by 2 here, but nothing guarantees it elsewhere.
                col_entry_indent: Optional[int] = None
                while k < min(cols_end, body_end):
                    col_entry = _RE_ENTRY.match(lines[k].rstrip("\n"))
                    if (
                        col_entry
                        and len(col_entry.group(1)) > key_indent
                        and (
                            col_entry_indent is None
                            or len(col_entry.group(1)) == col_entry_indent
                        )
                    ):
                        if col_entry_indent is None:
                            col_entry_indent = len(col_entry.group(1))
                        column = col_entry.group(2)
                        report["found_columns"].append(f"{model}.{column}")
                        col_indent = col_entry_indent + 2
                        col_start = k + 1
                        col_end = _span_end(lines, col_start, col_entry_indent)
                        desired_col = column_meta.get((model, column))
                        rendered_col = (
                            _render_column_meta(" " * col_indent, desired_col)
                            if desired_col
                            else None
                        )
                        lines, shift = _apply_meta(
                            lines, col_start, col_end, col_indent,
                            rendered_col, report, f"{model}.{column}",
                        )
                        body_end += shift
                        cols_end += shift
                        k = col_end + shift
                        continue
                    k += 1
                j = cols_end
                continue
            j += 1

        i = body_end
    return "".join(lines), report


