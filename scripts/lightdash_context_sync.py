def run_compile(cli: str, dbt_project: Path, meta_models: Set[str]) -> Dict[str, Any]:
    """`lightdash compile` with both offline flags — the no-server validation gate.

    The verdict distinguishes what the bridge caused from what it merely observed.
    Offline compile relies on YAML-declared column types (`--skip-warehouse-catalog`
    means "use types in yml"), so a project whose models declare no columns fails
    wholesale for a reason that predates this bridge — measured on enhanza-analytics:
    172 of 267 explores, none of them carrying bridge meta. Failing the stage for that
    is a gate going red on a correct state, which is how gates get switched off. So:
    `fail` only when a failing explore is one the bridge wrote meta on; otherwise the
    project's un-readiness is reported as `unready`, counted, never red.
    """
    cmd = [
        cli, "compile",
        "--project-dir", str(dbt_project),
        "--profiles-dir", str(dbt_project),
        "--skip-dbt-compile",
        "--skip-warehouse-catalog",
    ]
    # NO_COLOR/FORCE_COLOR: chalk otherwise ANSI-wraps "ERROR" in the per-explore
    # lines and the failing-explore matcher below sees nothing.
    env = dict(os.environ, CI="true", NO_COLOR="1", FORCE_COLOR="0")
    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True, cwd=str(dbt_project),
            timeout=300, env=env,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return {"status": "fail", "detail": f"lightdash compile did not run: {exc}"}
    output = (proc.stdout or "") + (proc.stderr or "")
    # The CLI adds PARTIAL_SUCCESS=y to the summary whenever any explore compiled
    # with warnings; the regex must tolerate both forms or a pre-existing failure
    # gets misread as "fail" through the tail-lines fallback.
    summary = re.search(
        r"Compiled (\d+) explores, SUCCESS=(\d+)(?: PARTIAL_SUCCESS=(\d+))? ERRORS=(\d+)",
        output,
    )
    if proc.returncode == 0:
        if not summary:
            return {"status": "ok", "detail": "ok"}
        detail = f"{summary.group(1)} explores"
        if summary.group(3) and int(summary.group(3)):
            detail += f", {summary.group(3)} partial (compile warnings)"
        return {"status": "ok", "detail": detail}

    failing = set(re.findall(r"^\s*-\s*ERROR>\s*(\S+)", output, re.MULTILINE))
    touched = sorted(failing & meta_models)
    if touched:
        return {
            "status": "fail",
            "detail": (
                f"{len(touched)} explore(s) carrying bridge meta fail offline "
                f"compile: {', '.join(touched[:5])}"
            ),
        }
    if summary:
        return {
            "status": "unready",
            "detail": (
                f"{summary.group(4)}/{summary.group(1)} explores fail offline compile "
                "with no bridge meta involved — models without YAML-declared columns "
                "have no types for `--skip-warehouse-catalog`; pre-existing, not "
                "introduced here"
            ),
        }
    tail = [ln for ln in output.strip().splitlines() if ln.strip()][-3:]
    return {"status": "fail", "detail": " / ".join(tail) or f"exit {proc.returncode}"}


