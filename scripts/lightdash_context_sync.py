def _patch_file(
    node: Dict[str, Any], man: Manifest, dbt_project: Path
) -> Optional[Path]:
    """The YAML file a model's patch lives in, resolved through package roots."""
    patch = node.get("patch_path") or ""
    if "://" not in patch:
        return None
    package, rel = patch.split("://", 1)
    if package == man.project_name:
        root = dbt_project
    else:
        root = package_roots(dbt_project).get(package)
    if root is None:
        return None
    path = root / rel
    return path if path.exists() else None


def sync(
    slug: str, manifest_arg: Optional[str], check: bool
) -> Dict[str, Any]:
    use_case = use_case_dir(slug)
    if use_case is None:
        die(f"no such use-case under skill-packs/*/use-cases/: {slug}")
        return {}

    dbt_project = use_case / "dbt_project"
    if not dbt_project.exists():
        return {"status": "skip", "reason": "no dbt_project yet"}

    if manifest_arg:
        manifest_path = Path(manifest_arg).resolve()
        target = (dbt_project / "target").resolve()
        if target not in manifest_path.parents:
            return {
                "status": "skip",
                "reason": (
                    "--manifest points outside dbt_project/target/ — the derivation "
                    "and `lightdash compile` must read the same generation; re-run "
                    "dbt parse there instead"
                ),
            }
    else:
        manifest_path = dbt_project / "target/manifest.json"
    if not manifest_path.exists():
        return {
            "status": "skip",
            "reason": "no manifest — dbt parse (or artifacts/refresh.sh)",
        }

    man = Manifest.load(str(manifest_path))
    joins, join_skips = derive_joins(man)
    participants: Set[str] = set(joins)
    for entries in joins.values():
        participants.update(e["join"] for e in entries)
    keys, ambiguous = derive_primary_keys(man, participants)
    annotations = load_annotations(use_case)
    column_meta, counts = derive_column_meta(man, annotations, participants)

    model_meta: Dict[str, Dict[str, Any]] = {}
    for model in participants:
        meta: Dict[str, Any] = {}
        if joins.get(model):
            meta["joins"] = joins[model]
        if model in keys:
            meta["primary_key"] = keys[model]
        if meta:
            model_meta[model] = meta

    # Group the desired meta by the schema file that declares each model.
    by_file: Dict[Path, Tuple[Dict[str, Dict[str, Any]], Dict[Tuple[str, str], Dict[str, Any]]]] = {}
    unplaced: List[str] = []
    models_by_name = {n.get("name"): n for n in man.models().values()}
    for model in sorted(set(model_meta) | {m for (m, _c) in column_meta}):
        node = models_by_name.get(model)
        path = _patch_file(node, man, dbt_project) if node else None
        if path is None:
            unplaced.append(f"{model}: declared in no resolvable schema file")
            continue
        file_models, file_columns = by_file.setdefault(path, ({}, {}))
        if model in model_meta:
            file_models[model] = model_meta[model]
        for (m, c), meta in column_meta.items():
            if m == model:
                file_columns[(m, c)] = meta

    # A file whose evidence disappeared entirely is in no desired set, so also
    # open every patch file still carrying the marker: regeneration must remove
    # orphaned blocks, not only rewrite live ones. Found by deleting a
    # relationships test and watching its join survive.
    for node in models_by_name.values():
        path = _patch_file(node, man, dbt_project) if node else None
        if path is None or path in by_file:
            continue
        try:
            if MARKER in path.read_text(encoding="utf-8"):
                by_file[path] = ({}, {})
        except OSError:
            continue

    changed: List[str] = []
    refused: List[Dict[str, str]] = []
    hand_authored: List[str] = []
    for path in sorted(by_file):
        text = path.read_text(encoding="utf-8")
        first = text.splitlines()[0] if text else ""
        if _FOREIGN_GENERATOR.match(first):
            refused.append(
                {
                    "file": str(path.relative_to(use_case)),
                    "reason": f"owned by another generator ({first.strip()[:60]})",
                }
            )
            continue
        file_models, file_columns = by_file[path]
        new_text, report = rewrite_yaml(text, file_models, file_columns)
        hand_authored += report["hand_authored"]
        # Desired meta that landed nowhere is reported, never silent: a YAML style
        # the rewriter's grammar cannot scan must show up here, not vanish.
        rel = str(path.relative_to(use_case))
        for missing in sorted(set(file_models) - set(report["found_models"])):
            unplaced.append(f"{missing}: model entry not found in {rel}")
        found_cols = set(report["found_columns"])
        for m, c in sorted(file_columns):
            if m in report["found_models"] and f"{m}.{c}" not in found_cols:
                unplaced.append(f"{m}.{c}: column entry not found in {rel}")
        if new_text != text:
            changed.append(rel)
            if not check:
                path.write_text(new_text, encoding="utf-8")

    translated, skipped, saved = classify_metricflow(man)
    knowledge_dir = use_case / "lightdash/knowledge"
    knowledge: Dict[str, Optional[str]] = {
        "semantic-coverage.md": coverage_markdown(
            slug, translated, skipped, saved, joins, join_skips
        ),
        "mcp.md": mcp_markdown(slug),
    }
    for name, content in knowledge.items():
        path = knowledge_dir / name
        if content is None:
            if path.exists():
                changed.append(str(path.relative_to(use_case)))
                if not check:
                    path.unlink()
            continue
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing != content:
            changed.append(str(path.relative_to(use_case)))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")

    cli = find_lightdash_cli()
    meta_models = set(model_meta) | {m for (m, _c) in column_meta}
    if check:
        # The currency gate is about bytes, not explores; the compile gate runs on
        # every real sync and in its own CLI-gated test, and skipping it here keeps
        # `--check` cheap enough to run in every suite pass.
        compile_result: Dict[str, Any] = {
            "status": "skip",
            "detail": "compile gate not run under --check; it runs on sync",
        }
    elif cli is None:
        compile_result = {
            "status": "skip",
            "detail": f"lightdash CLI not installed — {CLI_INSTALL}",
        }
    else:
        compile_result = run_compile(cli, dbt_project, meta_models)

    return {
        "status": "synced",
        "use_case": slug,
        "check": check,
        "joins": sum(len(v) for v in joins.values()),
        "join_models": len(joins),
        "joins_skipped": join_skips,
        "primary_keys": len(keys),
        "ambiguous_keys": ambiguous,
        "pii_hidden": counts["pii_hidden"],
        "ai_hints": counts["ai_hints"],
        "annotations_present": annotations is not None,
        "metricflow": {
            "translated": translated,
            "skipped": skipped,
            "saved_queries": saved,
        },
        "hand_authored": sorted(set(hand_authored)),
        "refused": refused,
        "unplaced": unplaced,
        "compile": compile_result,
        "changed": changed,
    }


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--use-case", required=True)
    parser.add_argument("--manifest")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--format", choices=("text", "json"), default="text")
    args = parser.parse_args(argv)

    payload = sync(args.use_case, args.manifest, args.check)

    if args.format == "json":
        print(json.dumps(payload))
    elif payload["status"] == "skip":
        print(f"skip  {args.use_case}: {payload['reason']}")
    else:
        mf = payload["metricflow"]
        print(
            f"{payload['joins']} join(s) on {payload['join_models']} model(s), "
            f"{payload['primary_keys']} primary key(s), "
            f"{payload['pii_hidden']} PII column(s) hidden, "
            f"{payload['ai_hints']} ai hint(s); "
            f"metricflow: {len(mf['translated'])} translated, "
            f"{len(mf['skipped'])} skipped; "
            f"compile: {payload['compile']['status']} ({payload['compile']['detail']})"
        )
        for entry in mf["skipped"]:
            print(f"  skipped {entry['name']}: {entry['reason']}")
        for name in payload["hand_authored"]:
            print(f"  hand-authored meta left alone: {name}")
        for entry in payload["refused"]:
            print(f"  refused {entry['file']}: {entry['reason']}")
        for rel in payload["changed"]:
            verb = "would change" if args.check else "changed"
            print(f"  {verb} {rel}")
        if payload["changed"] and not args.check:
            print(
                "  re-run dbt parse (artifacts/refresh.sh) so the manifest carries "
                "the new meta before `lightdash compile`/`deploy` reads it"
            )

    if payload["status"] == "synced" and payload["compile"]["status"] == "fail":
        return 1
    if args.check and payload.get("changed"):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
