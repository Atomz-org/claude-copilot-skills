def coverage_markdown(
    slug: str,
    translated: List[Dict[str, str]],
    skipped: List[Dict[str, str]],
    saved: List[str],
    joins: Dict[str, List[Dict[str, str]]],
    join_skips: List[str],
) -> Optional[str]:
    if not (translated or skipped or joins):
        return None
    lines = [_header(slug), "# Lightdash semantic coverage\n\n"]
    lines.append(
        "What of this project's semantic layer actually reaches Lightdash, and what\n"
        "does not. MetricFlow stays the metric's source of truth; the Lightdash CLI\n"
        f"(@lightdash/cli {CLI_PIN}, the external/lightdash submodule pin) translates\n"
        "the supported subset from `manifest.json` at compile/deploy time. Nothing\n"
        "below was re-authored as a Lightdash metric — a projection that dropped a\n"
        "filter or a window would be a wrong number that plans successfully.\n\n"
    )
    if translated:
        lines.append("## Metrics Lightdash translates natively\n\n")
        for m in translated:
            lines.append(f"- `{m['name']}` ({m['type']}, on `{m['model']}`)\n")
        lines.append("\n")
    if skipped:
        lines.append("## Metrics the translator skips — served by WrenAI, not Lightdash\n\n")
        lines.append(
            "Each of these has no faithful Lightdash representation. Query them\n"
            "through the Wren metric views (`wren/views/`), where the full MetricFlow\n"
            "definition — window, offset, cross-model join — is compiled into SQL.\n\n"
        )
        for m in skipped:
            lines.append(f"- `{m['name']}` ({m['type']}): {m['reason']}\n")
        lines.append("\n")
    if saved:
        lines.append("## Saved queries\n\n")
        lines.append(
            "The translator carries metrics only; saved queries are not translated.\n"
        )
        for name in saved:
            lines.append(f"- `{name}`\n")
        lines.append("\n")
    if joins:
        lines.append("## Explore joins derived from relationships tests\n\n")
        for child in sorted(joins):
            for join in joins[child]:
                rel = join.get("relationship", "cardinality untested — omitted")
                lines.append(f"- `{child}` → `{join['join']}` on `{join['sql_on']}` ({rel})\n")
        lines.append("\n")
    if join_skips:
        lines.append("## Relationships tests that produced no join\n\n")
        for reason in join_skips:
            lines.append(f"- {reason}\n")
        lines.append("\n")
    return "".join(lines)


