#!/usr/bin/env python3
"""Project dbt knowledge into Lightdash — joins, keys, PII hiding, and agent hints.

Lightdash is this repository's BI and agentic-analytics tier: the app is pinned as a
fork submodule at external/lightdash, the CLI as @lightdash/cli at the same release
(see docs/LIGHTDASH_INTEGRATION.md). Lightdash reads a dbt project directly, and since
its CLI translates MetricFlow metrics from the manifest natively (simple metrics, and
ratio/derived metrics whose inputs stay on one semantic model), **this bridge never
writes a metric**. A `meta.metrics` block restating a MetricFlow definition would be a
second source of truth — exactly what analytics rule 42 forbids.

What dbt cannot tell Lightdash, and what this script therefore owns:

- **Explore joins.** A dbt `relationships` test already declares the join — child,
  FK column, parent, parent field — so `models[].meta.joins` is derived from the tests,
  never invented. Cardinality comes only from `unique` tests (`many-to-one`, or
  `one-to-one` when the FK itself is unique-tested); where no unique test exists the
  `relationship:` key is omitted rather than guessed (rule 5). Join type is always
  `left`: MetricFlow joins dimension sources LEFT OUTER, and the Wren bridge measured
  an INNER join dropping guest-checkout orders from foreign-dim cuts.
- **Primary keys.** `meta.primary_key`, only on models that participate in a join and
  only when exactly one column carries both `unique` and `not_null` — an ambiguous key
  is reported, not chosen.
- **PII hiding.** A column whose `ontology/column-annotations.json` annotation says
  `pii: direct` gets `meta.dimension.hidden: true` in every model that declares it
  (rule 17: tagged at every model that carries it). `quasi` PII is not hidden — the
  right remedy differs per class — and a use-case without annotations hides nothing,
  reported as such rather than guessed at.
- **Agent hints.** Lightdash's AI agents read `ai_hint`. Annotated columns on join
  participants get their recorded definition, plus an additivity warning when the
  annotation says summing is wrong — the two facts a column name cannot convey.
- **The honest coverage statement.** `lightdash/knowledge/semantic-coverage.md` names
  which MetricFlow metrics the upstream translator will carry and which it skips
  (cumulative, conversion, time-offset, cross-model inputs or filters), so nobody
  reads a Lightdash project and believes it serves a metric it silently dropped.

Ownership follows the repository's insertion rules: meta blocks are inserted into the
project's own schema YAML **line-based, never a YAML round-trip** (these files carry
Jinja and comments a round-trip destroys), each block marked with an inline
`# generated: lightdash_context_sync` comment. A `meta:` without the marker is
hand-authored and left alone, reported. A file whose header names another generator
(`# GENERATED by scripts/ontology_to_dbt.py`) is refused whole — one generator never
edits another's file. Orphaned marker-owned blocks are removed on regeneration.

The no-server gate is `lightdash compile --skip-dbt-compile --skip-warehouse-catalog`:
it converts the manifest to explores and validates them entirely offline. No CLI means
skip with the remedy named, never a failure — the toolchain is optional here, like
rustc and Node everywhere else in this repository.

Nothing here reads or writes credentials. Deploying (`lightdash deploy`, previews) is
data egress and stays a human decision; the MCP registration line in
`lightdash/knowledge/mcp.md` uses environment placeholders, never token values.
"""

