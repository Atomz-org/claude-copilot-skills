#!/usr/bin/env python3
"""Derive the MetricFlow semantic layer from the annotated conformed columns.

This is the link between what a column *means* and what an agent can *ask*. Everything
upstream of here already exists: `dbt_column_memory.py` records which raw column feeds
which conformed one, `column_annotations.py` records what the conformed column is —
`role`, `additivity`, `unit`, `pii` — and `ontology_generator.py` projects both into
`index.json`. Everything downstream already exists too: `wren_context_sync.py` compiles
each MetricFlow metric to an MDL view, so `SELECT * FROM revenue` through the engine *is*
the metric, for BI and for an agent over the per-use-case MCP server.

The middle was empty. Measured on enhanza-analytics before this: **89 annotated conformed
columns, 17 of them measures, and zero semantic models** — so the Wren stage projected
nothing, and an agent asking "how many customers" got a table list rather than a metric.

The mapping is mechanical, because every facet already answers a MetricFlow question:

    role: identifier      -> entities        (primary when the grain is tested, else foreign)
    role: timestamp       -> dimensions      type: time, granularity from `unit: date`
    role: dimension|text|flag -> dimensions  type: categorical
    role: measure         -> measures        agg from `additivity`
    pii: direct           -> withheld        (rule 17)

What it will not do is supply the two facts nobody wrote down. **A primary entity comes
from a `unique` test, never from a name shape.** `CustomerId` looks like a key in every
model that carries it, and in a per-connector model it is one; in the union of six
connectors it is not, because two systems can issue the same id. A `unique` test is the
project stating the grain in a form that fails when it is wrong — which is exactly rule 21,
and the reason the semantic layer's coverage here is a direct function of test discipline
rather than of this script's cleverness. A model with no `unique` test is **skipped and
counted, with the test that unlocks it named**.

And **`agg: sum` comes from a recorded additivity, never from a numeric type** (rule 11).
An additive measure sums. A semi-additive one needs `non_additive_dimension` — naming which
dimension it may not cross is a decision, so it is refused. A non-additive one is not a
measure at all: store the numerator and the denominator and define the ratio as a metric.
A measure whose additivity nobody recorded is refused too, because `sum` is what a reader
already assumes and emitting it silently makes the assumption authoritative.

The layer is the consumer layer, not the union and not the per-connector model. Rule 43
puts semantic models on marts; rule 7 wants one entity defined once. `logic_bi_customers`
and `logic_bi_articles` each define their entity for the whole project — declaring
`customer` primary in nineteen `fortnox_bi_*`/`shopify_bi_*` models instead would be
nineteen definitions of one entity, which is the drift the conformed layer exists to
prevent. The prefix is imported from `ontology_to_dbt` rather than restated, so the
generator that writes those models and the generator that describes them cannot disagree
about which layer they are.

Usage:
    python3 scripts/ontology_to_semantic.py --use-case <slug> --dry-run
    python3 scripts/ontology_to_semantic.py --use-case <slug> --write
    python3 scripts/ontology_to_semantic.py --use-case <slug> --check
    python3 scripts/ontology_to_semantic.py --use-case <slug> --format json
"""

