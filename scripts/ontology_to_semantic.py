def tested_keys(man: Manifest) -> Dict[str, List[str]]:
    """Model name -> the columns a `unique` test declares unique.

    This is the grain, stated by the project in a form that fails when it is wrong. Nothing
    else in a dbt project says it: a column named `<Thing>Id` is a key in the model that
    issued it and not in the union of six systems that each issued their own.
    """
    keys: Dict[str, List[str]] = {}
    for node in man.nodes.values():
        if node.get("resource_type") != "test":
            continue
        if (node.get("test_metadata") or {}).get("name") != "unique":
            continue
        column = node.get("column_name")
        parents = (node.get("depends_on") or {}).get("nodes") or []
        if not column or not parents:
            continue
        owner = man.nodes.get(parents[0], {}).get("name")
        if owner:
            keys.setdefault(owner, []).append(column)
    return {model: sorted(set(cols)) for model, cols in keys.items()}


def not_null_columns(man: Manifest) -> Dict[str, List[str]]:
    """Model name -> the columns a `not_null` test covers.

    Read only to report the half of rule 21 a keyed model is missing. A primary entity
    column that is nullable is a real defect, but it is a defect in the *data*, not a
    reason to refuse to describe the model — so it warns rather than skips.
    """
    cols: Dict[str, List[str]] = {}
    for node in man.nodes.values():
        if node.get("resource_type") != "test":
            continue
        if (node.get("test_metadata") or {}).get("name") != "not_null":
            continue
        column = node.get("column_name")
        parents = (node.get("depends_on") or {}).get("nodes") or []
        if not column or not parents:
            continue
        owner = man.nodes.get(parents[0], {}).get("name")
        if owner:
            cols.setdefault(owner, []).append(column)
    return {model: sorted(set(c)) for model, c in cols.items()}


def has_time_spine(man: Manifest) -> bool:
    """Whether the project declares a MetricFlow time spine.

    Read from the manifest rather than by globbing for a filename, because the spine is
    whatever model carries a `time_spine:` block — dbt's own convention names it
    `metricflow_time_spine`, and this project's example does, but the name is not what
    makes it one.
    """
    if (man.data.get("semantic_manifest") or {}).get("time_spines"):
        return True
    for node in man.nodes.values():
        if node.get("resource_type") != "model":
            continue
        if node.get("time_spine") or (node.get("config") or {}).get("time_spine"):
            return True
        if node.get("name") == TIME_SPINE_MODEL:
            return True
    return False


def semantics_by_column(index: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    return {row["column"]: row for row in index.get("column_semantics") or []}


def contract_columns(memory: Dict[str, Any]) -> Dict[str, List[str]]:
    """Concept -> its conformed column list, in the order conformance agreed."""
    return {
        contract["concept"]: list(contract.get("conformed") or [])
        for contract in memory.get("contracts") or []
    }


