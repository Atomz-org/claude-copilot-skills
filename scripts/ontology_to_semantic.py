@dataclass
class Refusal:
    kind: str
    subject: str
    detail: str = ""

    def as_record(self) -> Dict[str, Any]:
        return {"kind": self.kind, "subject": self.subject, "detail": self.detail}


@dataclass
class SemanticModel:
    name: str
    concept: str
    dbt_model: str
    description: str
    primary: Tuple[str, str]  # (entity name, column)
    agg_time_dimension: Optional[str] = None
    foreign: List[Tuple[str, str]] = field(default_factory=list)
    time_dimensions: List[Tuple[str, str, str]] = field(default_factory=list)
    categorical: List[Tuple[str, str, str]] = field(default_factory=list)
    measures: List[Dict[str, str]] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)


def derive_model(
    concept: str,
    dbt_model: str,
    key_column: str,
    columns: List[str],
    semantics: Dict[str, Dict[str, Any]],
    joinable: Dict[str, str],
    refusals: List[Refusal],
) -> SemanticModel:
    """One semantic model from one keyed consumer model and its annotated columns.

    `joinable` maps a key column to the entity some *other* semantic model declares
    primary. An identifier that is not in it joins to nothing, and is reported rather than
    emitted — the same rule `connector_semantics_derive.py` applies to a dangling `*_id`.
    """
    taken = tuple(snake(c) for c in columns)
    model = SemanticModel(
        name=concept,
        concept=concept,
        dbt_model=dbt_model,
        description=f"Conformed {concept}. One row per {entity_name(key_column, taken)}, "
                    f"as declared by the `unique` test on {key_column}.",
        primary=(entity_name(key_column, taken), key_column),
    )
    claimed = {model.primary[0]}

    for column in columns:
        if column == key_column:
            continue
        facets = semantics.get(column)
        if not facets:
            refusals.append(Refusal(UNANNOTATED, f"{concept}.{column}"))
            continue
        if facets.get("pii") == "direct":
            # Rule 17. The column stays available upstream to anything with a reason to
            # join it; what it may not do is arrive in the layer BI and agents read.
            refusals.append(Refusal(PII_WITHHELD, f"{concept}.{column}"))
            continue

        role = facets.get("role")
        definition = (facets.get("definition") or "").strip()

        if role == "identifier":
            # An opaque id that reaches no primary entity is neither a join nor a useful
            # grouping: an agent that groups by it produces a report keyed on numbers
            # nobody can read, while the label column beside it is already a dimension.
            target = joinable.get(column)
            if not target:
                refusals.append(Refusal(
                    UNRESOLVED_ENTITY, f"{concept}.{column}",
                    "no semantic model declares it primary"))
                continue
            # The entity is named by whichever model declares it primary, so the name can
            # arrive already claimed by a local column. MetricFlow rejects a duplicate
            # element name, and silently dropping the join is better than an unparseable
            # file — but only if it is said out loud.
            # `taken` rather than `claimed` alone: a dimension later in the contract has not
            # been emitted yet but will claim its name, so checking only what has been
            # emitted so far would let the collision through in one column order and catch
            # it in another.
            if target in claimed or target in (set(taken) - {snake(column)}):
                refusals.append(Refusal(
                    UNRESOLVED_ENTITY, f"{concept}.{column}",
                    f"entity `{target}` collides with another element of {concept}"))
                continue
            claimed.add(target)
            model.foreign.append((target, column))
        elif role == "timestamp":
            granularity = GRANULARITY_FOR_UNIT.get(facets.get("unit") or "")
            if not granularity:
                refusals.append(Refusal(
                    NO_TIME, f"{concept}.{column}",
                    "role: timestamp with no `unit: date` — granularity not recorded"))
                continue
            model.time_dimensions.append((snake(column), column, granularity))
            claimed.add(snake(column))
        elif role in CATEGORICAL_ROLES:
            model.categorical.append((snake(column), column, definition))
            claimed.add(snake(column))
        elif role == "measure":
            measure = derive_measure(concept, column, facets, refusals)
            if measure:
                model.measures.append(measure)
        else:
            refusals.append(Refusal(UNANNOTATED, f"{concept}.{column}",
                                    f"role: {role or 'unset'}"))

    # An entity count is not a business decision: the `unique` test is what makes
    # count_distinct on this column exactly the number of things. It is also the one
    # measure a dimension model can carry honestly, which is why the semantic layer is
    # useful before a single fact table declares its grain.
    model.measures.insert(0, {
        "name": f"{model.primary[0]}_count",
        "agg": "count_distinct",
        "expr": key_column,
        "description": f"Distinct {model.primary[0]} count. Exact: {key_column} carries a "
                       f"`unique` test.",
    })

    # Rule 44: measures need an aggregation time dimension. One candidate is the model's
    # answer; several is a choice, and choosing changes every metric's default time grain.
    if len(model.time_dimensions) == 1:
        model.agg_time_dimension = model.time_dimensions[0][0]
    elif len(model.time_dimensions) > 1:
        refusals.append(Refusal(
            AMBIGUOUS_TIME, concept,
            "several time dimensions: " + ", ".join(t[0] for t in model.time_dimensions)))
    else:
        refusals.append(Refusal(NO_TIME, concept, "no annotated time dimension"))

    return model


def derive_measure(
    concept: str, column: str, facets: Dict[str, Any], refusals: List[Refusal]
) -> Optional[Dict[str, str]]:
    """A measure, or a refusal naming which decision is missing (rule 11)."""
    additivity = facets.get("additivity")
    if additivity == "non_additive":
        refusals.append(Refusal(
            NON_ADDITIVE, f"{concept}.{column}",
            "store the numerator and the denominator and define the ratio as a metric"))
        return None
    if additivity == "semi_additive":
        refusals.append(Refusal(
            SEMI_ADDITIVE, f"{concept}.{column}",
            "declare which dimension it may not be summed across"))
        return None
    agg = AGG_FOR_ADDITIVITY.get(additivity or "")
    if not agg:
        refusals.append(Refusal(
            UNRECORDED_ADDITIVITY, f"{concept}.{column}",
            "annotate `additivity` before this column can be aggregated"))
        return None
    description = (facets.get("definition") or "").strip()
    unit = facets.get("unit")
    if unit and description:
        description = f"{description} Unit: {unit}."
    return {
        "name": snake(column),
        "agg": agg,
        "expr": column,
        "description": description or f"{column}, summed.",
    }


def derive(use_case: Path, man: Manifest) -> Dict[str, Any]:
    """Every semantic model the annotated columns and the tested grains support."""
    index = _load(use_case / "ontology" / "index.json", "index.json")
    memory = _load(use_case / "ontology" / "column-memory.json", "column-memory.json")

    semantics = semantics_by_column(index)
    contracts = contract_columns(memory)
    keys = tested_keys(man)
    not_nulls = not_null_columns(man)
    model_names = {
        node["name"] for node in man.nodes.values() if node.get("resource_type") == "model"
    }

    refusals: List[Refusal] = []
    eligible: List[Tuple[str, str, str]] = []  # (concept, dbt model, key column)

    for concept in sorted(contracts):
        dbt_model = f"{LOGIC_PREFIX}{concept}"
        if dbt_model not in model_names:
            refusals.append(Refusal(
                NO_MODEL, concept,
                f"no {dbt_model} — run ontology_to_dbt.py --write"))
            continue
        candidates = keys.get(dbt_model) or []
        if not candidates:
            refusals.append(Refusal(
                NO_KEY, concept,
                f"{dbt_model} declares no `unique` test — rule 21"))
            continue
        if len(candidates) > 1:
            refusals.append(Refusal(
                NO_KEY, concept,
                f"{dbt_model} declares {len(candidates)} unique columns "
                f"({', '.join(candidates)}); which one is the grain is a decision"))
            continue
        eligible.append((concept, dbt_model, candidates[0]))

    # Two passes, because a foreign entity is only real once something declares it primary.
    # Resolving them in one pass would emit a join key for every `*Id` in the contract and
    # let an agent write a join that plans and returns nothing.
    joinable: Dict[str, str] = {}
    for concept, _dbt_model, key_column in eligible:
        taken = tuple(snake(c) for c in contracts[concept])
        joinable[key_column] = entity_name(key_column, taken)

    models: List[SemanticModel] = []
    for concept, dbt_model, key_column in eligible:
        model = derive_model(concept, dbt_model, key_column, contracts[concept],
                             semantics, joinable, refusals)
        if key_column not in (not_nulls.get(dbt_model) or []):
            model.warnings.append(
                f"{dbt_model}.{key_column} has `unique` but no `not_null` — rule 21 wants both")
        models.append(model)

    return {"models": models, "refusals": refusals}


