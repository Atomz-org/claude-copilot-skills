GENERATED_MARKER = "GENERATED by scripts/ontology_to_semantic.py"
SEMANTIC_DIR = "models/semantic"
SEMANTIC_FILE = "_semantic_models__generated.yml"

# A role that is a dimension you group by. `identifier` becomes an entity instead, and a
# `measure` becomes a measure; anything else is a column nobody classified.
CATEGORICAL_ROLES = ("dimension", "text", "flag")

# MetricFlow needs a granularity on every time dimension (rule 44) and there is exactly one
# evidence source for it here: the annotation's own unit. A `role: timestamp` with no
# `unit: date` is a column whose granularity nobody recorded.
GRANULARITY_FOR_UNIT = {"date": "day"}

# The only additivity that maps to an aggregation without a further decision.
AGG_FOR_ADDITIVITY = {"additive": "sum"}

# Why a candidate did not become part of the semantic layer. Classified rather than
# counted, because "no grain declared" and "PII withheld" are two different owners.
NO_KEY = "no-unique-test"
NO_MODEL = "no-consumer-model"
NO_TIME = "no-time-dimension"
AMBIGUOUS_TIME = "several-time-dimensions"
PII_WITHHELD = "pii-withheld"
SEMI_ADDITIVE = "semi-additive-needs-non-additive-dimension"
NON_ADDITIVE = "non-additive-not-a-measure"
UNRECORDED_ADDITIVITY = "additivity-not-recorded"
UNRESOLVED_ENTITY = "identifier-joins-to-nothing"
UNANNOTATED = "unannotated"

# dbt refuses to parse a project whose semantic layer has a time dimension and no time
# spine — not "cumulative metrics are unavailable", the whole parse. Every stage downstream
# of here reads the manifest, so writing the file into a project without one would take the
# ontology, the seeds, the graph merge and the Wren project down with it.
TIME_SPINE_MODEL = "metricflow_time_spine"


