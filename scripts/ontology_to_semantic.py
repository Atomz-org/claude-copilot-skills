def snake(name: str) -> str:
    """`AccountId` -> `account_id`, `FileURL` -> `file_url`, `OrgId` -> `org_id`."""
    text = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", text)
    return re.sub(r"_+", "_", text).strip("_").lower()


def entity_name(column: str, taken: Tuple[str, ...] = ()) -> str:
    """The entity a key column identifies.

    `CustomerId` identifies a `customer`. The suffix is dropped because MetricFlow joins on
    the entity *name*, so `customer` in a dimension model and `customer` in a fact model
    are the same entity — which is the whole point of conformance. Keeping the `_id` would
    still work, but the resulting semantic layer reads as a schema rather than a business.

    Except where dropping it collides. `dim_accounts` carries `MainAccountId` *and*
    `MainAccount` — the key and its label — and stripping the suffix names both
    `main_account`. MetricFlow requires element names to be unique within a semantic model,
    so the stripped form is used only when no other column in the same model already
    answers to it; `AccountClassId` beside `AccountClass` is the same case.
    """
    stripped = re.sub(r"_?id$", "", snake(column)) or snake(column)
    return stripped if stripped not in taken else snake(column)


