def summarise(payload: Dict[str, Any]) -> Dict[str, Any]:
    models: List[SemanticModel] = payload["models"]
    refusals: List[Refusal] = payload["refusals"]
    by_kind: Dict[str, int] = {}
    for refusal in refusals:
        by_kind[refusal.kind] = by_kind.get(refusal.kind, 0) + 1
    with_measures = [m for m in models if m.agg_time_dimension]
    return {
        "semantic_models": len(models),
        "with_measures": len(with_measures),
        "entities": sum(1 + len(m.foreign) for m in models),
        "dimensions": sum(len(m.time_dimensions) + len(m.categorical) for m in models),
        "measures": sum(len(m.measures) for m in with_measures),
        "metrics": sum(len(m.measures) for m in with_measures),
        "refused": by_kind,
        "warnings": [w for m in models for w in m.warnings],
    }


def run(slug: str, manifest: Optional[Path], write: bool, check: bool) -> Dict[str, Any]:
    use_case = use_case_dir(slug)
    manifest = manifest or _paths.default_manifest(use_case)
    if not manifest or not manifest.exists():
        return {"status": "skip", "reason": "no manifest — run artifacts/refresh.sh"}
    for artifact in ("index.json", "column-memory.json"):
        if not (use_case / "ontology" / artifact).exists():
            return {"status": "skip", "reason": f"no ontology/{artifact}"}

    project = _paths.project_root_of(manifest, use_case)
    if project is None:
        return {"status": "skip", "reason": "no dbt project beside the manifest"}

    man = Manifest.load(str(manifest))
    payload = derive(use_case, man)
    summary = summarise(payload)
    summary["status"] = "ok"

    target = project / SEMANTIC_DIR / SEMANTIC_FILE
    summary["path"] = str(target.relative_to(REPO))
    summary["refusals"] = [r.as_record() for r in payload["refusals"]]

    # Found by writing the file and parsing: a `time` dimension with no time spine is not a
    # missing feature, it is `Parsing Error ... none was found` and dbt builds nothing. The
    # columns, ontology, seeds, graph and wren stages all read the manifest, so a generator
    # that emitted here would take the whole use-case down to add one metric. The spine is
    # not derivable either — it needs `dbt_utils` in packages.yml and a start date that is
    # a decision, and this project declares only per-org `start_years: {}`.
    if payload["models"] and not has_time_spine(man):
        summary["status"] = "skip"
        summary["reason"] = (
            f"{len(payload['models'])} semantic model(s) ready, but the project declares no "
            f"MetricFlow time spine — dbt would refuse to parse. Add a {TIME_SPINE_MODEL} "
            f"model (dbt_utils.date_spine) and re-run; --dry-run shows what lands."
        )
        summary["changed"] = []
        return summary

    content = render(slug, payload["models"])
    existing = target.read_text(encoding="utf-8") if target.exists() else None
    changed = existing != content
    if changed and write and not check:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    summary["changed"] = [summary["path"]] if changed else []
    return summary


def report(summary: Dict[str, Any]) -> None:
    if summary.get("status") == "skip":
        print(f"semantic: skip — {summary['reason']}")
        # A skip that hid the derivation would make the blocker look like an absence of
        # work. Everything below is what lands the moment the reason is resolved.
        if not summary.get("semantic_models"):
            return
    print(f"semantic models: {summary['semantic_models']} "
          f"({summary['with_measures']} carry measures)")
    print(f"  entities {summary['entities']} · dimensions {summary['dimensions']} · "
          f"measures {summary['measures']} · metrics {summary['metrics']}")
    refused = summary.get("refused") or {}
    if refused:
        print("  refused:")
        for kind, count in sorted(refused.items(), key=lambda kv: -kv[1]):
            print(f"    {count:>4}  {kind}")
    for warning in summary.get("warnings") or []:
        print(f"  warn: {warning}")
    if summary.get("changed"):
        print(f"  would write: {summary['changed'][0]}")


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Derive MetricFlow semantic models from the annotated conformed columns."
    )
    parser.add_argument("--use-case", required=True)
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--write", action="store_true", help="write the generated YAML")
    parser.add_argument("--dry-run", action="store_true", help="report without writing")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the generated file is stale")
    parser.add_argument("--format", choices=("text", "json"), default="text")
    parser.add_argument("--limit", type=int, default=40,
                        help="refusals listed in --format json (default 40)")
    args = parser.parse_args(argv)

    summary = run(args.use_case, args.manifest, write=args.write, check=args.check)
    if args.format == "json":
        summary = dict(summary)
        summary["refusals"] = (summary.get("refusals") or [])[: args.limit]
        print(json.dumps(summary, sort_keys=True))
    else:
        report(summary)
    if args.check and summary.get("changed"):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
